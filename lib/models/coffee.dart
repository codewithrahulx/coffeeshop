class Coffee {
  final int id;
  final String name;
  final String subtitle;
  final String category;
  final String image;
  final String description;
  final double price;
  final double rating;
  final int reviews;

  const Coffee({
    required this.id,
    required this.name,
    required this.subtitle,
    required this.category,
    required this.image,
    required this.description,
    required this.price,
    required this.rating,
    required this.reviews,
  });
}